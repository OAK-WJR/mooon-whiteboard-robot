# PlatformIO pre-build script: embeds the gzipped web page and writes the
# OTA token and a build id to include/build_info.h. The token lives in c6_wall/.ota_token (gitignored)
# and is shared by the firmware and tools/ota.py.
import gzip
import os
import secrets
import time

Import("env")  # noqa: F821  (provided by PlatformIO)

root = env.subst("$PROJECT_DIR")  # noqa: F821
token_path = os.path.join(root, ".ota_token")
if not os.path.exists(token_path):
    with open(token_path, "w") as f:
        f.write(secrets.token_hex(12))
with open(token_path) as f:
    token = f.read().strip()

with open(os.path.join(root, "web", "index.html"), "rb") as f:
    page = gzip.compress(f.read(), compresslevel=9, mtime=0)
lines = ["// Generated by tools/prebuild.py from web/index.html. Do not edit.", "#pragma once", "#include <stddef.h>",
         "#include <stdint.h>", f"static const size_t WEB_PAGE_GZ_LEN = {len(page)};",
         "static const uint8_t WEB_PAGE_GZ[] = {"]
for i in range(0, len(page), 24):
    lines.append("  " + ",".join(str(b) for b in page[i:i + 24]) + ",")
lines.append("};")
out = os.path.join(root, "include", "web_page.h")
text = "\n".join(lines) + "\n"
if not os.path.exists(out) or open(out).read() != text:
    with open(out, "w") as f:
        f.write(text)

# A header (not -D flags) so only main.cpp recompiles when the build id changes.
info = os.path.join(root, "include", "build_info.h")
with open(info, "w") as f:
    f.write("#pragma once\n#define WBB_OTA_TOKEN \"%s\"\n#define WBB_BUILD_ID \"%s\"\n" % (token, time.strftime("%m%d-%H%M%S")))
